import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { HOME_PATH } from '../seo.config.js';
import { PUBLIC_PAGES } from '../site-pages-content.js';
import { resolveBuildSiteOrigin } from './resolve-site-origin.mjs';

const publicDir = resolve('public');
const siteUrl = resolveBuildSiteOrigin('production');
const homeUrl = `${siteUrl}${HOME_PATH}`;
const lastmod = new Date().toISOString().slice(0, 10);

const urls = [
  { loc: homeUrl, changefreq: 'daily', priority: '1.0' },
  ...Object.values(PUBLIC_PAGES).map((page) => ({
    loc: `${siteUrl}${page.path}`,
    changefreq: 'monthly',
    priority: '0.8',
  })),
];

await mkdir(publicDir, { recursive: true });

await writeFile(
  resolve(publicDir, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs. Only public, crawlable URLs belong here. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((url) => `  <url>
    <loc>${url.loc}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${url.changefreq}</changefreq>
    <priority>${url.priority}</priority>
  </url>`).join('\n')}
</urlset>
`,
  'utf8'
);

await writeFile(
  resolve(publicDir, 'robots.txt'),
  `User-agent: *
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`,
  'utf8'
);

console.log(`SEO files generated for ${siteUrl} (${urls.length} public URLs).`);
