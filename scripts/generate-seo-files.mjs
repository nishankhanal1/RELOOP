import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { loadEnv } from 'vite';
import {
  DEFAULT_SITE_URL,
  HOME_PATH,
  normalizeSiteOrigin,
  resolveSiteOrigin,
} from '../seo.config.js';

const viteEnv = loadEnv('production', process.cwd(), 'VITE_');
const publicDir = resolve('public');
const explicitSiteUrl = process.env.VITE_SITE_URL || viteEnv.VITE_SITE_URL;

if (explicitSiteUrl && !normalizeSiteOrigin(explicitSiteUrl)) {
  console.error('VITE_SITE_URL must be a clean HTTPS origin, for example https://reloop-iota-blue.vercel.app');
  process.exit(1);
}

const siteUrl = resolveSiteOrigin(
  explicitSiteUrl,
  process.env.VERCEL_PROJECT_PRODUCTION_URL,
  process.env.URL,
  DEFAULT_SITE_URL
);
const homeUrl = `${siteUrl}${HOME_PATH}`;
const lastmod = new Date().toISOString().slice(0, 10);

await mkdir(publicDir, { recursive: true });

await writeFile(
  resolve(publicDir, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs. Only public, crawlable URLs belong here. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${homeUrl}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>daily</changefreq>
    <priority>1.0</priority>
  </url>
</urlset>
`,
  'utf8'
);

await writeFile(
  resolve(publicDir, 'robots.txt'),
  `User-agent: *
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`,
  'utf8'
);

console.log(`SEO files generated for ${siteUrl} (${homeUrl}).`);
