import { mkdir, readFile, unlink, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { loadEnv } from 'vite';

const viteEnv = loadEnv('production', process.cwd(), 'VITE_');
const rawSiteUrl = process.env.VITE_SITE_URL || viteEnv.VITE_SITE_URL || process.env.URL || process.env.VERCEL_PROJECT_PRODUCTION_URL;
const publicDir = resolve('public');

if (!rawSiteUrl) {
  console.warn('VITE_SITE_URL is not set; sitemap.xml will not be generated. Set it to the canonical production origin before deploying.');
  await mkdir(publicDir, { recursive: true });
  const sitemapPath = resolve(publicDir, 'sitemap.xml');
  try {
    const currentSitemap = await readFile(sitemapPath, 'utf8');
    if (currentSitemap.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by Reloop SEO build script -->')) await unlink(sitemapPath);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  await writeFile(resolve(publicDir, 'robots.txt'), 'User-agent: *\nAllow: /\n', 'utf8');
  process.exit(0);
}

let siteUrl;
try {
  const parsed = new URL(rawSiteUrl.startsWith('https://') ? rawSiteUrl : `https://${rawSiteUrl}`);
  if (parsed.protocol !== 'https:' || parsed.pathname !== '/' || parsed.search || parsed.hash) throw new Error();
  siteUrl = parsed.origin;
} catch {
  console.error('VITE_SITE_URL must be an HTTPS origin, for example https://www.example.com');
  process.exit(1);
}

await mkdir(publicDir, { recursive: true });
await writeFile(resolve(publicDir, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by Reloop SEO build script -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${siteUrl}/</loc></url>\n</urlset>\n`, 'utf8');
await writeFile(resolve(publicDir, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`, 'utf8');
